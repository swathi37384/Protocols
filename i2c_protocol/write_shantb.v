`timescale 1ns / 1ps

module tb_I2C_protocol;

    //========================================================
    // Testbench signals
    //========================================================
    reg clk;
    reg rst_n;
    reg start;

    reg [6:0] addr;
    reg [7:0] data;

    wire scl;
    wire sda;

    wire busy;
    wire ack_error;


    //========================================================
    // Slave ACK control
    //========================================================
    reg slave_ack;

    // Slave pulls SDA LOW when slave_ack = 1
    assign sda = slave_ack ? 1'b0 : 1'bz;


    //========================================================
    // DUT
    //========================================================
    I2C_protocol uut
    (
        .clk       (clk),
        .rst_n     (rst_n),
        .start     (start),
        .addr      (addr),
        .data      (data),
        .scl       (scl),
        .sda       (sda),
        .busy      (busy),
        .ack_error (ack_error)
    );


    //========================================================
    // Clock generation
    // 10 ns clock period = 100 MHz
    //========================================================
    always #5 clk = ~clk;


    //========================================================
    // Test sequence
    //========================================================
    initial
    begin

        // Initialize signals
        clk       = 1'b0;
        rst_n     = 1'b0;
        start     = 1'b0;

        addr      = 7'b1010000;
        data      = 8'b10101010;

        slave_ack = 1'b0;


        //====================================================
        // Reset
        //====================================================
        #20;

        rst_n = 1'b1;


        //====================================================
        // Start I2C write
        //====================================================
        #20;

        start = 1'b1;

        #10;

        start = 1'b0;


        //======================================
